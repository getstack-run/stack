import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import type { ManifestInlineSchemaEntry } from '@stack/shared';

// schemas-inline bundle loader.
//
// The bundle is regenerated whenever a
// claim-type Zod schema changes. The bundle file is committed (a
// generated artefact that lives in git so prod boots cleanly without
// running the script).
//
// Module-scoped cache: first call reads + parses; subsequent calls
// hit memory. Safe for the lifetime of one API process; rotation on
// schema changes happens at boot time after the build pipeline
// regenerates the file.
let _schemasBundleCache: Record<string, ManifestInlineSchemaEntry> | null = null;
async function loadSchemasBundle(): Promise<Record<string, ManifestInlineSchemaEntry>> {
  if (_schemasBundleCache !== null) return _schemasBundleCache;
  // Resolve the bundle path relative to the config directory, the parent of
  // this wiring directory (apps/api/src/config, or apps/api/dist/config when
  // compiled). The bundle is in packages/shared/src/generated/ (kept in src so
  // it's source-committed and survives a clean build).
  const configDir = dirname(dirname(fileURLToPath(import.meta.url)));
  const candidates = [
    join(configDir, '..', '..', '..', 'packages', 'shared', 'src', 'generated', 'schemas-bundle.json'),
    join(
      configDir,
      '..',
      '..',
      '..',
      '..',
      'packages',
      'shared',
      'src',
      'generated',
      'schemas-bundle.json',
    ),
  ];
  for (const path of candidates) {
    try {
      const raw = readFileSync(path, 'utf8');
      _schemasBundleCache = JSON.parse(raw) as Record<string, ManifestInlineSchemaEntry>;
      return _schemasBundleCache;
    } catch {
      // fall through
    }
  }
  // Bundle missing → empty inline schemas. Don't crash the boot path, but
  // every evidence-pack export is then refused (503) by the pack builder,
  // which never pins a placeholder hash. The production image copies the
  // bundle (apps/api/Dockerfile), so this is a developer-environment
  // condition.
  console.warn(
    '[schemas-bundle] could not load schemas-bundle.json:', 'no candidate path had it; schemas_inline will be empty until `pnpm run schemas:publish` runs',
  );
  _schemasBundleCache = {};
  return _schemasBundleCache;
}

/**
 * The inline schema entries for an evidence-pack manifest: the shared claim
 * envelope plus one entry per claim type in the pack. The bundle is the
 * build-time artefact at `packages/shared/src/generated/schemas-bundle.json`
 * (also published as a static asset for external consumers), regenerated by
 * `pnpm run schemas:publish` whenever a claim-type Zod schema changes.
 */
export async function resolveInlineSchemas(
  claimTypes: ReadonlySet<string>,
): Promise<Record<string, ManifestInlineSchemaEntry>> {
  const bundle = await loadSchemasBundle();
  const out: Record<string, ManifestInlineSchemaEntry> = {};
  // Always emit the envelope entry — every signed claim shares
  // this wrapper, so verifiers ALWAYS need it.
  const envelope = bundle['envelope'];
  if (envelope) out['envelope'] = envelope;
  for (const claimType of claimTypes) {
    const entry = bundle[claimType];
    if (entry) out[claimType] = entry;
  }
  return out;
}
