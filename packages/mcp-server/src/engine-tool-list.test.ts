async function listedTools(options?: Parameters<typeof createStackMcpServer>[2]): Promise<string[]> {
  const server = createStackMcpServer('http://api.test', 'sk_test_unused', options);
  const [clientTransport, serverTransport] = InMemoryTransport.createLinkedPair();
  const client = new Client({ name: 'engine-tool-list-test', version: '0.0.0' });
  await Promise.all([server.connect(serverTransport), client.connect(clientTransport)]);
  const names = (await client.listTools()).tools.map((tool) => tool.name);
  await client.close();
  return names;
}

describe('the engine MCP tool list', () => {
  it('is exactly the pinned list when the server is built with its defaults', async () => {
    expect((await listedTools()).sort()).toEqual([...ENGINE_TOOLS].sort());
  });

  it('is the same list, with nothing added, for a platform-staff session', async () => {
    expect((await listedTools({ isPlatformStaff: true })).sort()).toEqual([...ENGINE_TOOLS].sort());
  });

  it('names no tool twice and keeps the list sorted', () => {
    expect(new Set(ENGINE_TOOLS).size).toBe(ENGINE_TOOLS.length);
    expect(ENGINE_TOOLS).toEqual([...ENGINE_TOOLS].sort());
  });
});
