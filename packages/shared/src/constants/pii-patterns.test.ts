import { describe, it, expect } from 'vitest';
import { scanForPii, PII_PATTERNS } from './pii-patterns/index.js';

describe('scanForPii — email', () => {
  it('matches simple email', () => {
    const m = scanForPii('contact me at jane@example.com tomorrow');
    expect(m).toHaveLength(1);
    expect(m[0]!.category).toBe('email');
    expect(m[0]!.matchedText).toBe('jane@example.com');
  });

  it('matches plus-tag + subdomain', () => {
    const m = scanForPii('a.b+tag@mail.example.co.uk');
    expect(m).toHaveLength(1);
    expect(m[0]!.matchedText).toBe('a.b+tag@mail.example.co.uk');
  });

  it('does not match string without @', () => {
    expect(scanForPii('definitely not an email here')).toHaveLength(0);
  });

  it('does not match string without TLD', () => {
    expect(scanForPii('foo@bar')).toHaveLength(0);
  });
});

describe('scanForPii — ssn_us', () => {
  it('matches valid SSN', () => {
    const m = scanForPii('SSN 123-45-6789 on file');
    expect(m).toHaveLength(1);
    expect(m[0]!.category).toBe('ssn_us');
  });

  it('does not match 000-XX-XXXX (zero leading group)', () => {
    expect(scanForPii('000-12-3456')).toHaveLength(0);
  });

  it('does not match 9XX-XX-XXXX (ITIN range)', () => {
    expect(scanForPii('912-34-5678')).toHaveLength(0);
  });

  it('does not match 666-XX-XXXX', () => {
    expect(scanForPii('666-12-3456')).toHaveLength(0);
  });
});

describe('scanForPii — phone_us', () => {
  it('matches +1 prefix with dashes, as an international number', () => {
    // Scoring changed which pattern wins this span. A leading + makes it
    // E.164, and pii_phone_intl (0.5) outranks pii_phone_us (0.3), so the
    // more specific reading takes it. Still one match, still redacted.
    const m = scanForPii('Call +1-415-555-0142 please');
    expect(m).toHaveLength(1);
    expect(m[0]!.category).toBe('phone_intl');
  });

  it('matches parens form when labelled', () => {
    const m = scanForPii('phone (212) 555-1234.');
    expect(m).toHaveLength(1);
    expect(m[0]!.category).toBe('phone_us');
  });

  it('leaves an unlabelled ten-digit run alone', () => {
    // Ten digits in 3-3-4 is almost anything: an order number, a reference,
    // a timestamp. Without a word like "phone" nearby it is not evidence.
    expect(scanForPii('Number is (212) 555-1234.')).toHaveLength(0);
  });
});

