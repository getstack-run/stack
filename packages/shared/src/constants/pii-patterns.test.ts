describe('scanForPii — overlap resolution', () => {
  // A Swedish personnummer is matched span-for-span by pii_phone_us. Before
  // overlap resolution both were returned, and the redactor spliced the same
  // span twice and corrupted the text around it.
  it('returns exactly one match for a span two patterns both claim', () => {
    const m = scanForPii('pnr 811218-9876 end');
    expect(m).toHaveLength(1);
    expect(m[0]!.pattern_id).toBe('pii_personnummer_se');
  });

  it('never returns two matches that share any character', () => {
    const m = scanForPii('pnr 811218-9876 tel +46 70 174 06 05 mail a@b.se card 4111111111111111');
    for (let i = 0; i < m.length; i++) {
      for (let j = i + 1; j < m.length; j++) {
        const a = m[i]!;
        const b = m[j]!;
        expect(a.startOffset < b.endOffset && b.startOffset < a.endOffset).toBe(false);
      }
    }
  });

  it('a splice-by-offset redaction leaves no original value behind', () => {
    const text = 'pnr 811218-9876 mail a@b.se card 4111111111111111';
    let out = text;
    for (const m of scanForPii(text)) {
      out = out.slice(0, m.startOffset) + `[REDACTED:${m.category}]` + out.slice(m.endOffset);
    }
    expect(out).not.toContain('811218-9876');
    expect(out).not.toContain('a@b.se');
    expect(out).not.toContain('4111111111111111');
  });

  it('falls back to the loose phone pattern when the check digit fails and a phone label is present', () => {
    // The personnummer validator rejects this, so the span is left to
    // pii_phone_us — which now needs its own keyword to clear the threshold.
    const m = scanForPii('phone 811218-9875 end');
    expect(m).toHaveLength(1);
    expect(m[0]!.pattern_id).toBe('pii_phone_us');
  });

  it('redacts nothing when the check digit fails and nothing labels it', () => {
    expect(scanForPii('num 811218-9875 end')).toHaveLength(0);
  });

  it('prefers the higher-scoring pattern on a contested span', () => {
    // 811218-9876 is a valid personnummer AND an exact pii_phone_us match.
    // Labelled as a personnummer it scores 0.80 against phone_us's 0.30, so
    // score decides before length or catalog order ever come into it.
    const m = scanForPii('personnummer 811218-9876');
    expect(m).toHaveLength(1);
    expect(m[0]!.pattern_id).toBe('pii_personnummer_se');
    expect(m[0]!.score).toBeGreaterThan(0.7);
  });
});

describe('scanForPii — country scoping', () => {
  it('drops patterns outside the operator\'s countries', () => {
    // A valid Croatian OIB, labelled. An operator working only in Sweden has
    // no reason to run the Croatian scheme, and dropping it is what buys them
    // a threshold low enough to catch bare Swedish formats.
    const text = 'oib: 12345678903';
    expect(scanForPii(text).some((m) => m.pattern_id === 'pii_oib_hr')).toBe(true);
    expect(scanForPii(text, { countries: ['SE'] })).toHaveLength(0);
  });

  it('keeps country-neutral patterns whatever the scope', () => {
    // Narrowing to Sweden must not stop redacting credit cards or email.
    const m = scanForPii('mail a@b.se card 4111111111111111', { countries: ['SE'] });
    expect(m.some((x) => x.category === 'email')).toBe(true);
    expect(m.some((x) => x.category === 'credit_card')).toBe(true);
  });

  it('scoping plus a low threshold catches a bare format safely', () => {
    // The combination that actually solves the problem: a Dutch operator
    // scopes to NL, drops the threshold, and now an unlabelled BSN redacts
    // while a random nine-digit run still does not, because every other
    // country's nine-digit scheme has been taken out of the running.
    const opts = { countries: ['NL'], threshold: 0.2 };
    expect(scanForPii('order 111222333 shipped', opts).some((m) => m.pattern_id === 'pii_bsn_nl')).toBe(true);
    // 123456780 fails the elfproef, so it is not a BSN and stays put.
    expect(scanForPii('order 123456780 shipped', opts)).toHaveLength(0);
  });

  it('an unknown country code scopes to nothing but the neutral patterns', () => {
    const m = scanForPii('personnummer 811218-9876', { countries: ['ZZ'] });
    expect(m).toHaveLength(0);
  });
});

describe('scanForPii — false-positive ceiling', () => {
  // Before scoring, an unlabelled digit run was redacted 5.0% of the time
  // overall, peaking at 13.3% for nine digits. Scoring drops the six
  // bare-format schemes below the default threshold, which is where nearly
  // all of that came from. Overall is now 0.5%, a tenfold improvement, and
  // the sampled text ("order N shipped") deliberately carries no keyword, so
  // anything firing here is firing on the digits alone.
  //
  // Eleven digits keeps a higher ceiling than the rest, at a measured 1.5%.
  // Five schemes with a birth date and a check digit live at that length
  // (Greece, Hungary, Estonia, Latvia, Belgium) and no one of them dominates:
  // they contribute 50-75 hits each. Dropping them to the weak tier would fix
  // the number by making five countries need a label, which trades real
  // coverage for a rounder figure. Left as is, and stated.
  const ceilings: Array<[number, number]> = [
    [8, 0.01],
    [9, 0.01],
    [10, 0.01],
    [11, 0.02],
    [12, 0.01],
    [13, 0.01],
  ];

  for (const [len, ceiling] of ceilings) {
    it(`${len}-digit runs stay under ${(ceiling * 100).toFixed(0)}% false positives`, () => {
      // Deterministic LCG: the number has to be reproducible run to run.
      let seed = 20260805;
      const nextDigit = () => Math.floor((((seed = (seed * 1103515245 + 12345) & 0x7fffffff) / 0x7fffffff)) * 10);
      const N = 4000;
      let hits = 0;
      for (let i = 0; i < N; i++) {
        const s = Array.from({ length: len }, nextDigit).join('');
        if (scanForPii(`order ${s} shipped`).some((x) => x.category === 'national_id')) hits++;
      }
      expect(hits / N).toBeLessThan(ceiling);
    });
  }
});

describe('PII_PATTERNS catalog shape', () => {
  it('all patterns have unique id', () => {
    const ids = new Set(PII_PATTERNS.map((p) => p.id));
    expect(ids.size).toBe(PII_PATTERNS.length);
  });

  it('validated national identifiers are ordered before the loose phone patterns', () => {
    // Load-bearing: overlap resolution breaks ties by catalog order, so a
    // check-digit-validated identifier must outrank an unvalidated span.
    const firstPhone = PII_PATTERNS.findIndex((p) => p.category === 'phone_us' || p.category === 'phone_intl');
    const lastNationalId = PII_PATTERNS.map((p) => p.category).lastIndexOf('national_id');
    expect(lastNationalId).toBeLessThan(firstPhone);
  });

  it('every national identifier carries a validator', () => {
    for (const p of PII_PATTERNS.filter((x) => x.category === 'national_id')) {
      expect(p.validator, `${p.id} has no validator`).toBeTypeOf('function');
    }
  });

  it('all patterns have valid regex source', () => {
    for (const p of PII_PATTERNS) {
      expect(() => new RegExp(p.source, p.flags)).not.toThrow();
    }
  });
});
